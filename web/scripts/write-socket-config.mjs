/**
 * Writes web/public/angelic-socket-config.js so static deploys can point Socket.IO
 * at a real server (Railway, Render, etc.). Set VITE_SOCKET_URL or ANGELIC_SOCKET_URL
 * in CI/Vercel — origin only, e.g. https://your-app.up.railway.app (no /socket.io path).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const webRoot = path.resolve(__dirname, '..')
const repoRoot = path.resolve(webRoot, '..')
const outPublic = path.join(webRoot, 'public', 'angelic-socket-config.js')
const outRepo = path.join(repoRoot, 'angelic-socket-config.js')

const url = (process.env.VITE_SOCKET_URL || process.env.ANGELIC_SOCKET_URL || '').trim()
const body =
    '/* Auto-generated by write-socket-config.mjs — set VITE_SOCKET_URL or ANGELIC_SOCKET_URL for admin + game */\n' +
    `window.__ANGELIC_SOCKET_URL = ${JSON.stringify(url)};\n`

fs.mkdirSync(path.dirname(outPublic), { recursive: true })
fs.writeFileSync(outPublic, body, 'utf8')
fs.writeFileSync(outRepo, body, 'utf8')
console.log(
    '[write-socket-config]',
    url ? 'Wrote socket origin from env' : 'Wrote empty string (same-origin io(); use env for production API)',
)
